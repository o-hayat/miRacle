import { build } from "esbuild";
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const manifest = JSON.parse(await readFile("public/data/manifest.json", "utf8"));
for (const [name, expected] of Object.entries(manifest.source_hashes ?? {})) {
  const bytes = await readFile(`../${name}`);
  if (createHash("sha256").update(bytes).digest("hex") !== expected) {
    throw new Error(`Scientific source ${name} changed. Run the pinned Python asset exporter with --fixtures before building.`);
  }
}
await writeFile(
  "src/lib/data-version.ts",
  `// Generated by scripts/build-worker.mjs\nexport const DATA_VERSION = ${JSON.stringify(manifest.version)};\n`,
);

const result = await build({
  entryPoints: ["src/lib/analysis/worker.ts"],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
});
const contents = result.outputFiles[0].contents;
const hash = createHash("sha256").update(contents).digest("hex").slice(0, 16);
await mkdir("public/workers", { recursive: true });
await writeFile(`public/workers/analysis-${hash}.js`, contents);
await writeFile(
  "src/lib/worker-path.ts",
  `// Generated by scripts/build-worker.mjs\nexport const WORKER_PATH = "/workers/analysis-${hash}.js";\n`,
);
